"""Column-width figure for the yield-reliability screening experiment.

    python scripts/make_figure_yield_screen.py

Reads results/triage/yield_screen.json and yield_per_field.csv -- both
generated by scripts/yield_screen.py -- and draws nothing that is not in
them. Two panels:

  left   the label-free signal against the error it is meant to predict,
         one marker per field-season, coloured by the unreliability label,
         with the Spearman coefficient and the independent-unit count shown
         so the sample size cannot be mistaken for 41.
  right  recall against realised workload with plot-bootstrap intervals,
         and the random-referral diagonal. If the intervals straddle the
         diagonal the figure says so, because that is the result.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

PROJ = Path(__file__).resolve().parents[1]
OUT = PROJ / "results" / "figures_ieee"
RES = PROJ / "results" / "triage" / "yield_screen.json"
CSV = PROJ / "results" / "triage" / "yield_per_field.csv"
W = 3.35

plt.rcParams.update({"font.size": 7.2, "figure.dpi": 400,
                     "savefig.bbox": "tight", "axes.grid": True,
                     "grid.alpha": 0.25, "axes.axisbelow": True,
                     "axes.titlesize": 7.4, "legend.fontsize": 6.0,
                     "xtick.labelsize": 6.4, "ytick.labelsize": 6.4,
                     "axes.labelsize": 7.0, "lines.linewidth": 1.3,
                     "savefig.pad_inches": 0.02})


def main() -> int:
    if not RES.exists() or not CSV.exists():
        raise SystemExit(f"run scripts/yield_screen.py first; missing {RES}")
    r = json.loads(RES.read_text(encoding="utf8"))
    rows = list(csv.DictReader(CSV.open(encoding="utf8")))

    sig = np.array([float(x["disagreement_cv"]) for x in rows])
    ape = np.array([float(x["ape_pct"]) for x in rows])
    bad = np.array([x["is_bad"] == "1" for x in rows])

    # Stacked, not side by side: this is placed inside a 3.3 in IEEE
    # column, and a two-panel row drawn at page width gets clipped there.
    fig, ax = plt.subplots(2, 1, figsize=(W, 4.05),
                           constrained_layout=True)

    # ---- left: signal vs error
    ax[0].scatter(sig[~bad], ape[~bad], s=16, c="#2e7d32", alpha=0.85,
                  label=f"reliable (n={int((~bad).sum())})",
                  edgecolors="none")
    ax[0].scatter(sig[bad], ape[bad], s=16, c="#c0392b", alpha=0.85,
                  label=f"unreliable (n={int(bad.sum())})", edgecolors="none")
    ax[0].axhline(r["ape_threshold"], color="grey", lw=0.8, ls=":")
    ax[0].set_xlabel("inter-model disagreement (CV of predictions)")
    ax[0].set_ylabel("ensemble-mean APE (%)")
    ax[0].set_title(
        f"Spearman {r['threshold_free']['spearman_signal_vs_ape']:+.2f}  |  "
        f"AUROC {r['threshold_free']['auroc']:.2f}", fontsize=7.0)
    ax[0].legend(loc="upper left", framealpha=0.9)

    # ---- right: recall vs workload with the random diagonal
    s = r["screening"]
    wl = np.array([x["workload_realised"] for x in s])
    rc = np.array([x["recall"] for x in s])
    lo = np.array([x["recall_ci"]["lo"] for x in s])
    hi = np.array([x["recall_ci"]["hi"] for x in s])
    ax[1].plot([0, 1], [0, 1], ls=":", color="grey", lw=0.9,
               label="random referral")
    ax[1].errorbar(wl, rc, yerr=[rc - lo, hi - rc], marker="o", ms=4,
                   capsize=2.5, color="#1f3b73", lw=1.3,
                   label="inter-model disagreement")
    ax[1].set_xlim(0, 1); ax[1].set_ylim(0, 1.05)
    ax[1].set_xlabel("field-seasons referred (workload)")
    ax[1].set_ylabel("unreliable field-seasons caught")
    ax[1].xaxis.set_major_formatter(lambda v, _: f"{v:.0%}")
    ax[1].yaxis.set_major_formatter(lambda v, _: f"{v:.0%}")
    straddles = all(x["recall_ci"]["lo"] <= x["workload_realised"] for x in s)
    ax[1].set_title(
        ("every interval includes random referral"
         if straddles else "intervals clear random referral at some workload"),
        fontsize=6.8)
    ax[1].legend(loc="lower right", framealpha=0.9)

    for a in ax:
        a.tick_params(pad=1.5)
    fig.text(0.5, -0.022,
             f"{r['n_field_seasons']} field-seasons from {r['n_plots']} "
             f"plots; independent unit = plot (n = {r['n_plots']}).",
             ha="center", fontsize=6.0)

    OUT.mkdir(parents=True, exist_ok=True)
    f = OUT / "fig_yield_screen.png"
    fig.savefig(f)
    plt.close(fig)
    print(f"  wrote {f}")
    print(f"  {r['n_field_seasons']} field-seasons, {r['n_plots']} plots, "
          f"AUROC {r['threshold_free']['auroc']:.3f}, verdict "
          f"{r['verdict']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
