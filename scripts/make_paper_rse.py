    anchor = ref_head._p.getprevious()
    prev = Paragraph(anchor, ref_head._parent)
    h = head(prev, "CRediT authorship contribution statement")
    credit = CREDIT or PROPOSED["credit"]
    txt = " ".join(f"{k}: {v}." for k, v in credit.items())
