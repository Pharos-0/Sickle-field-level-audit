# ---------------------------------------------------------------- helpers
def _strip_diacritics(s: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFKD", s)
                   if not unicodedata.combining(c))


def _set_cols(section, n=1):
    for c in section._sectPr.xpath("./w:cols"):
        c.set(qn("w:num"), str(n))


def _clear(p):
    for r in list(p.runs):
        r._element.getparent().remove(r._element)


def _remove(el):
    el._element.getparent().remove(el._element)


def _insert_after(p, text="", bold=False, italic=False, size=12,
                  align=WD_ALIGN_PARAGRAPH.LEFT):
    new = OxmlElement("w:p")
    p._p.addnext(new)
    from docx.text.paragraph import Paragraph
    q = Paragraph(new, p._parent)
    q.alignment = align
    if text:
        r = q.add_run(text)
        r.bold, r.italic, r.font.size = bold, italic, Pt(size)
    return q


def _pending(p, label, text, size=12):
    r = p.add_run(f"TO CONFIRM ({label}): ")
    r.bold = True
    r.font.size = Pt(size)
    r.font.highlight_color = WD_COLOR_INDEX.YELLOW
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.highlight_color = WD_COLOR_INDEX.YELLOW


ROMAN = {"I": 1, "II": 2, "III": 3, "IV": 4, "V": 5, "VI": 6, "VII": 7,
         "VIII": 8, "IX": 9, "X": 10}


def _secref(roman, letter=None):
    s = str(ROMAN[roman])
    return s if letter is None else f"{s}.{ord(letter) - 64}"


CITE_GROUP = re.compile(r"\[(\d+)\](?:,\s*\[\d+\])*")


