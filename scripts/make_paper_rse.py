    # figures: wider in one column, captions at 10 pt
    for shp in doc.inline_shapes:
        w, h = shp.width, shp.height
        scale = min(Inches(6.0) / w, 1.8)
        shp.width, shp.height = int(w * scale), int(h * scale)
    for p in body_paras:
        if re.match(r"Fig\. \d+\.", p.text):
            for r in p.runs:
                r.text = re.sub(r"^(Fig\. \d+\.)\s+", r"\1 ", r.text)
